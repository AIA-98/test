import random

def calculate_probabilities(excluded_sets, range_main):
    frequency = {i: 0 for i in range(1, range_main + 1)}
    total_draws = len(excluded_sets)

    for draw in excluded_sets:
        for number in draw:
            frequency[number] += 1

    probabilities = {i: frequency[i] / total_draws for i in range(1, range_main + 1)}
    return probabilities

def weighted_random_selection(range_main, num_numbers, probabilities):
    numbers = list(range(1, range_main + 1))
    weights = [probabilities[num] for num in numbers]
    draw = random.choices(numbers, weights=weights, k=num_numbers)
    return draw

def is_unique(draw, existing_draws_set):
    return tuple(draw) not in existing_draws_set

def generate_unique_lottery_numbers(num_draws, num_numbers, range_main, existing_draws):
    existing_draws_set = set(tuple(draw) for draw in existing_draws)
    unique_draws = []

    while len(unique_draws) < num_draws:
        probabilities = calculate_probabilities(existing_draws, range_main)
        draw = []

        while len(draw) < num_numbers:
            choice = weighted_random_selection(range_main, 1, probabilities)[0]  # Pick one at a time
            if choice not in draw:
                draw.append(choice)

        if is_unique(draw, existing_draws_set):
            unique_draws.append(sorted(draw))  # Sorting here to keep it consistent
            existing_draws_set.add(tuple(draw))

    return unique_draws


